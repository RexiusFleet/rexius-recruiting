  'when it matches a positions.jotform_option_label for the same location.';
comment on column recruiting.applications.source is
  'How they heard about the job, cleaned (Indeed.com, Rexius.com, Craigslist.com, Google, '
  'Facebook, Referral, Walk In, Other, ...). source_detail keeps the free-text "other" answer.';
