-- Phase 3b: the Jotform forms, applications, their files, review status, status history, and
-- the candidate contact log.
--
-- Access rules (CLAUDE.md sections 5 and 7):
--   * applications, application_status, status_history, contacts, application_files: admin and
--     hr read and write. Managers have NO direct access to any of these tables; they read a
--     curated view (20261026000300) that leaves out notes, the raw `answers` JSON, and anything
--     offer-related.
--   * forms: anyone with a profile can read (labels for the UI); admin and hr can change.
--   * service_role: all, for the backfill and the webhook, which are the only writers of
--     applications and application_files.
--
-- Personal information (CLAUDE.md section 5): `answers` holds the cleaned submission with the
-- driver licence (30, 31, 35), signature (238, 333, 369) and initials (324-332) answers already
-- removed by the importer. Nothing here stores SSNs, bank details, dates of birth, government
-- IDs, or wages, and no column exists for them.

-- ---------------------------------------------------------------------------------------------
-- Enums
-- ---------------------------------------------------------------------------------------------

create type recruiting.file_kind as enum ('resume', 'portfolio', 'other');
create type recruiting.contact_kind as enum ('email', 'call', 'text', 'in_person');
create type recruiting.contact_direction as enum ('outbound', 'inbound');

-- ---------------------------------------------------------------------------------------------
-- forms: the Jotform forms and their question maps. Seeded in 20261026000400; refreshed by
-- the backfill/webhook code when Jotform's question list changes.
-- ---------------------------------------------------------------------------------------------

create table recruiting.forms (
  id              smallint generated by default as identity primary key,
  jotform_form_id text not null unique check (jotform_form_id ~ '^[0-9]+$'),
  label           text not null check (length(btrim(label)) > 0),
  language        text not null default 'en' check (language in ('en', 'es')),
  default_location text,
  questions       jsonb not null default '{}'::jsonb,
  field_map       jsonb not null default '{}'::jsonb,
  is_active       boolean not null default true,
  updated_at      timestamptz not null default now()
);

comment on table recruiting.forms is
  'One row per Jotform form that feeds the app. `questions` is Jotform''s question list keyed by '
  'question ID (label, type, order, options); `field_map` maps app fields (name, email, position, '
  'source, resume, ...) to question IDs for this form, plus the never-import list.';
comment on column recruiting.forms.default_location is
  'Location to store when the form has no location question (the CAS form stores "CAS").';
comment on column recruiting.forms.field_map is
  'Keys are app field names from CLAUDE.md section 4; values are question IDs as strings, or '
  'objects for compound fields (position per location, employer blocks). The `never_import` key '
  'lists question IDs dropped before `answers` is written.';

create trigger forms_set_updated_at
  before update on recruiting.forms
  for each row execute function recruiting.set_updated_at();

alter table recruiting.forms enable row level security;

create policy "forms: app users can read forms"
  on recruiting.forms for select to authenticated
  using (recruiting.current_role() is not null);

create policy "forms: staff can add forms"
  on recruiting.forms for insert to authenticated
  with check (recruiting.is_staff());

create policy "forms: staff can change forms"
  on recruiting.forms for update to authenticated
  using (recruiting.is_staff())
  with check (recruiting.is_staff());

create policy "forms: staff can remove forms"
  on recruiting.forms for delete to authenticated
  using (recruiting.is_staff());

grant select, insert, update, delete on recruiting.forms to authenticated;
grant all on recruiting.forms to service_role;

