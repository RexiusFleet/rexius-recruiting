-- ---------------------------------------------------------------------------------------------
-- Triggers: first stage on insert, history on stage change
-- ---------------------------------------------------------------------------------------------

-- The stage new applications start in: the lowest sort_order.
create or replace function recruiting.first_stage_id()
returns smallint
language sql
stable
security definer
set search_path = ''
as $$
  select s.id from recruiting.stages s order by s.sort_order limit 1;
$$;

revoke execute on function recruiting.first_stage_id() from public;
grant execute on function recruiting.first_stage_id() to authenticated, service_role;

create or replace function recruiting.init_application_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_stage smallint := recruiting.first_stage_id();
begin
  if v_stage is null then
    raise exception 'recruiting.stages is empty; seed the pipeline before importing applications';
  end if;
  insert into recruiting.application_status (application_id, stage_id, stage_since, updated_by)
  values (new.id, v_stage, new.submitted_at, auth.uid());
  insert into recruiting.status_history (application_id, from_stage_id, to_stage_id, changed_by, changed_at)
  values (new.id, null, v_stage, auth.uid(), new.submitted_at);
  return new;
end;
$$;

comment on function recruiting.init_application_status() is
  'After insert on applications: create the application_status row in the first stage and the '
  'opening status_history row, both dated at submission time.';

revoke execute on function recruiting.init_application_status() from public;

create trigger applications_init_status
  after insert on recruiting.applications
  for each row execute function recruiting.init_application_status();

create or replace function recruiting.log_stage_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.stage_id is distinct from old.stage_id then
    new.stage_since := now();
    new.updated_by := coalesce(auth.uid(), new.updated_by);
    insert into recruiting.status_history (application_id, from_stage_id, to_stage_id, changed_by)
    values (new.application_id, old.stage_id, new.stage_id, auth.uid());
  end if;
  return new;
end;
$$;

comment on function recruiting.log_stage_change() is
  'Before update on application_status: when stage_id changes, stamp stage_since/updated_by and '
  'append a status_history row.';

revoke execute on function recruiting.log_stage_change() from public;

create trigger application_status_log_stage_change
  before update of stage_id on recruiting.application_status
  for each row execute function recruiting.log_stage_change();

