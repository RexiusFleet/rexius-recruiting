create type recruiting.position_status as enum ('draft', 'open', 'closed');
create type recruiting.posting_channel as enum
  ('rexius_com', 'indeed', 'craigslist', 'google_ads', 'referral', 'other');

comment on type recruiting.position_status is
  'draft: being written. open: accepting applicants. closed: filled or withdrawn.';
comment on type recruiting.posting_channel is
  'Where a position was advertised. Matches the source values applicants pick on the forms, '
  'roughly: Rexius.com -> rexius_com, Indeed.com -> indeed, Craigslist.com -> craigslist, '
  'Google -> google_ads, Referral -> referral, everything else -> other.';

-- ---------------------------------------------------------------------------------------------
-- stages: the pipeline. Admin-editable; seeded in 20261026000400.
-- ---------------------------------------------------------------------------------------------

create table recruiting.stages (
  id          smallint generated by default as identity primary key,
  name        text not null unique check (length(btrim(name)) > 0),
  sort_order  smallint not null unique,
  is_terminal boolean not null default false,
  is_hired    boolean not null default false,
  check (not is_hired or is_terminal)
);

comment on table recruiting.stages is
  'Pipeline stages in display order. is_terminal: the application is finished (hired, not '
  'selected, withdrawn). is_hired marks the one terminal stage that counts as a hire for reports.';

alter table recruiting.stages enable row level security;

create policy "stages: app users can read stages"
  on recruiting.stages for select to authenticated
  using (recruiting.current_role() is not null);

create policy "stages: admins can add stages"
  on recruiting.stages for insert to authenticated
  with check (recruiting.current_role() = 'admin');

create policy "stages: admins can change stages"
  on recruiting.stages for update to authenticated
  using (recruiting.current_role() = 'admin')
  with check (recruiting.current_role() = 'admin');

create policy "stages: admins can remove stages"
  on recruiting.stages for delete to authenticated
  using (recruiting.current_role() = 'admin');

grant select, insert, update, delete on recruiting.stages to authenticated;
grant all on recruiting.stages to service_role;

-- ---------------------------------------------------------------------------------------------
-- positions: open and past roles. filled_by_application_id is added in 20261026000200 once
-- applications exists; description_doc_id is added in 20261026000300 once documents exists.
-- ---------------------------------------------------------------------------------------------

create table recruiting.positions (
  id                   uuid primary key default gen_random_uuid(),
  title                text not null check (length(btrim(title)) > 0),
  location             text not null check (length(btrim(location)) > 0),
  department           text,
  hiring_manager       text,
  pay_min              numeric(10, 2) check (pay_min is null or pay_min >= 0),
  pay_max              numeric(10, 2) check (pay_max is null or pay_max >= 0),
  pay_unit             text check (pay_unit is null or pay_unit in ('hour', 'year')),
  status               recruiting.position_status not null default 'draft',
  opened_at            date,
  closed_at            date,
  jotform_option_label text,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  check (pay_min is null or pay_max is null or pay_min <= pay_max),
  check (closed_at is null or opened_at is null or closed_at >= opened_at)
);

comment on table recruiting.positions is
  'Roles Rexius hires for, open or past. One row per opening; a role hired for again later gets '
  'a new row so time-to-fill and cost-per-hire stay per opening.';
comment on column recruiting.positions.jotform_option_label is
  'The exact option text in the English form''s position dropdown for this location. Used to '
  'link applications to positions at import and to flag drift between the form and this table.';
comment on column recruiting.positions.pay_unit is
  'hour or year. Pay ranges here are the advertised range, never an individual''s wage.';

create index positions_status_idx on recruiting.positions (status);
create index positions_location_idx on recruiting.positions (location);
create index positions_option_label_idx on recruiting.positions (location, jotform_option_label);

create trigger positions_set_updated_at
  before update on recruiting.positions
  for each row execute function recruiting.set_updated_at();

alter table recruiting.positions enable row level security;

create policy "positions: app users can read positions"
  on recruiting.positions for select to authenticated
  using (recruiting.current_role() is not null);

create policy "positions: staff can add positions"
  on recruiting.positions for insert to authenticated
  with check (recruiting.is_staff());

create policy "positions: staff can change positions"
  on recruiting.positions for update to authenticated
  using (recruiting.is_staff())
  with check (recruiting.is_staff());

create policy "positions: staff can remove positions"
  on recruiting.positions for delete to authenticated
  using (recruiting.is_staff());

grant select, insert, update, delete on recruiting.positions to authenticated;
grant all on recruiting.positions to service_role;

-- ---------------------------------------------------------------------------------------------
-- postings: where a position was advertised
-- ---------------------------------------------------------------------------------------------

create table recruiting.postings (
  id           uuid primary key default gen_random_uuid(),
  position_id  uuid not null references recruiting.positions (id) on delete cascade,
  channel      recruiting.posting_channel not null,
  url          text,
  utm_source   text,
  utm_campaign text,
  posted_at    date not null default current_date,
  ended_at     date,
  notes        text,
  created_at   timestamptz not null default now(),
  check (ended_at is null or ended_at >= posted_at)
);

comment on table recruiting.postings is
  'One row per place a position was advertised. Spend and traffic figures hang off it in '
  'channel_spend.';

create index postings_position_idx on recruiting.postings (position_id);
create index postings_channel_idx on recruiting.postings (channel);

