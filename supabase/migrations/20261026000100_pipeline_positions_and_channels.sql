-- ---------------------------------------------------------------------------------------------
-- channel_spend: hand-entered figures per posting per period. Staff only.
-- ---------------------------------------------------------------------------------------------

create table recruiting.channel_spend (
  id           uuid primary key default gen_random_uuid(),
  posting_id   uuid not null references recruiting.postings (id) on delete cascade,
  period_start date not null,
  period_end   date not null,
  spend        numeric(10, 2) not null default 0 check (spend >= 0),
  views        integer check (views is null or views >= 0),
  applies      integer check (applies is null or applies >= 0),
  notes        text,
  created_at   timestamptz not null default now(),
  check (period_end >= period_start),
  unique (posting_id, period_start, period_end)
);

comment on table recruiting.channel_spend is
  'Spend, views and applies for a posting over a period, typed in from the channel''s own '
  'reporting. Reports divide spend by applicants and hires per channel.';

create index channel_spend_posting_idx on recruiting.channel_spend (posting_id, period_start);

alter table recruiting.channel_spend enable row level security;

