-- Phase 3a: shared helpers, the pipeline stages, and the positions side of the model
-- (positions, postings, channel_spend). Applications follow in 20261026000200.
--
-- Access rules (CLAUDE.md section 7, docs/database-conventions.md):
--   * admin and hr: read and write everything here.
--   * manager: read stages, positions and postings (they need them to make sense of the
--     tracker); no access to channel_spend.
--   * no profile: nothing.
--   * anon: nothing (no usage on the schema).
--   * service_role: all, for the backfill script and the webhook.

-- ---------------------------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------------------------

-- True when the caller is admin or hr. Every "staff can write" policy uses it.
create or replace function recruiting.is_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select recruiting.current_role() in ('admin', 'hr');
$$;

comment on function recruiting.is_staff() is
  'True for admin and hr. Managers and users without a profile get false.';

revoke execute on function recruiting.is_staff() from public;
grant execute on function recruiting.is_staff() to authenticated, service_role;

-- Keeps an updated_at column current. Attach as `before update` on tables that have one.
create or replace function recruiting.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

comment on function recruiting.set_updated_at() is
  'Trigger function: sets new.updated_at = now() before an update.';

revoke execute on function recruiting.set_updated_at() from public;

-- ---------------------------------------------------------------------------------------------
-- Enums
